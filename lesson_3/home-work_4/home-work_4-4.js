/**
 * 4.4
 * Умова: Дано ціле число. З'ясувати, чи воно є простим 
 * (простим називається число, більше ніж 1, які не мають інших дільників крім 1 і себе).
 */
const n = getRandomInt(1, 100);
let isPrime = n > 1;
for (let i = 2; i * i <= n; i++) {
    if (n % i === 0) {
        isPrime = false;
        break;
    }
}
console.log(isPrime ? `${n} є простим` : `${n} не є простим`);
